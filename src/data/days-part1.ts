const monthDates = (startDay: number, daysInMonth: number, monthName: string, yearDays: number[]) => {
  const out: { date: string; isoDate: string }[] = [];
  for (let i = 0; i < daysInMonth; i++) {
    const d = i + 1;
    out.push({
      date: `${monthName} ${String(d).padStart(2, '0')}`,
      isoDate: `2026-${String(yearDays[i]).padStart(2, '0')}-${String(d).padStart(2, '0')}`,
    });
  }
  return out;
};

